"""Resolve SYMFLUENCE framework names across core releases.

SYMFLUENCE moved its shared modelling infrastructure under
``symfluence.core.modeling`` (ADR 0011,
docs/adr/0011-retire-unused-back-compat-shims.md in the SYMFLUENCE repository).
The old ``symfluence.models.base`` paths still import, but they emit
``DeprecationWarning`` and will be removed before SYMFLUENCE 1.0. The new path
does not exist in symfluence 0.9.2 and earlier, which this plugin still
supports, so it is tried first and the legacy path is used only when the
canonical module is missing.

Drop the fallback (and import straight from ``symfluence.core.modeling``) once
this plugin requires the first symfluence release after 0.9.2.
"""

_CANONICAL = "symfluence.core.modeling.base.base_config"

try:
    from symfluence.core.modeling.base.base_config import AutoGeneratedConfigAdapter
except ModuleNotFoundError as _exc:  # symfluence <= 0.9.2
    # Fall back only when the canonical module itself is absent; a missing
    # third-party dependency must still surface.
    _missing = _exc.name or ""
    if not (_CANONICAL == _missing or _CANONICAL.startswith(_missing + ".")):
        raise
    from symfluence.models.base.base_config import AutoGeneratedConfigAdapter

__all__ = ["AutoGeneratedConfigAdapter"]
